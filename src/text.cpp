int textWidth(const std::string& text, int scale) {
    if (text.empty()) return 0;
    return static_cast<int>(text.size()) * 6 * scale - scale;  // 5 px glyph + 1 px gap, minus the last gap
}

int textHeight(int scale) { return 7 * scale; }

void drawText(Canvas& canvas, int x, int y, const std::string& text, Color color, int scale) {
    int penX = x;
    for (char ch : text) {
        const Glyph& g = glyphFor(ch);
        for (int row = 0; row < 7; ++row) {
            for (int col = 0; col < 5; ++col) {
                if (g.rows[row] & (1 << (4 - col))) {
                    for (int dy = 0; dy < scale; ++dy)
                        for (int dx = 0; dx < scale; ++dx) canvas.setPixel(penX + col * scale + dx, y + row * scale + dy, color);
                }
            }
        }
        penX += 6 * scale;
    }
}

